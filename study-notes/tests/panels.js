// Screenshots of interactive panels (settings, flashcards, highlighter list, search) for visual review.
const { chromium } = require('playwright');
const path = require('path');
const file = 'file://' + path.resolve(__dirname, '../dist/法国大革命及其历史意义.html');
const SHOT = '/tmp/claude-0/-home-user-deepgemm/6e1807bd-796a-562f-95f3-008ab9433b1b/scratchpad';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, colorScheme: process.argv[2] || 'light' });
  const page = await ctx.newPage();
  await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  await page.goto(file);
  await page.waitForTimeout(500);
  await page.evaluate(() => {
    const t = document.querySelector('#s3-2-4 ~ * li, #s3-2 li');
    const w = document.createTreeWalker(document.getElementById('s3-2'), NodeFilter.SHOW_TEXT);
    let n; while ((n = w.nextNode()) && n.nodeValue.length < 30);
    const r = document.createRange(); r.setStart(n, 2); r.setEnd(n, 20);
    getSelection().removeAllRanges(); getSelection().addRange(r);
    n.parentElement.scrollIntoView({ block: 'center' });
  });
  await page.waitForTimeout(300);
  await page.screenshot({ path: SHOT + '/p-select.png' });
  await page.click('#hl-bar .pen.c-yellow');
  await page.waitForTimeout(200);
  await page.click('mark.hl');
  await page.waitForTimeout(200);
  await page.screenshot({ path: SHOT + '/p-pop.png' });
  await page.keyboard.press('Escape');
  await page.click('.side-tab[data-tab="hl"]');
  await page.fill('#q', '拿破仑 法典');
  await page.waitForTimeout(500);
  await page.screenshot({ path: SHOT + '/p-search.png' });
  await page.fill('#q', '');
  await page.click('#tools-top [data-tool="flash"]');
  await page.waitForTimeout(300);
  await page.screenshot({ path: SHOT + '/p-flash.png' });
  await page.click('#fc-stage .fc-card');
  await page.waitForTimeout(600);
  await page.screenshot({ path: SHOT + '/p-flash-back.png' });
  await page.click('#m-flash [data-close]');
  await page.click('#tools-top [data-tool="settings"]');
  await page.waitForTimeout(200);
  await page.screenshot({ path: SHOT + '/p-settings.png' });
  await page.click('#m-settings [data-close]');
  await page.click('.side-tab[data-tab="key"]');
  await page.click('#tools-top [data-tool="maskkw"]');
  await page.click('#tools-top [data-tool="masknum"]');
  await page.evaluate(() => document.getElementById('s4-4').scrollIntoView());
  await page.waitForTimeout(300);
  await page.screenshot({ path: SHOT + '/p-masks.png' });
  await browser.close();
})();
